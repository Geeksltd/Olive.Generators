using System;
using System.Linq;
using System.Reflection;
using Olive;

namespace OliveGenerator
{
    static class Extensions
    {
        /// <summary>The base class of every generated command.</summary>
        const string GeneratedBaseClass = "Olive.EventBusMessage";

        /// <summary>
        /// Gets the members which the command class is generated from, i.e. its public instance
        /// properties and fields. Unlike a DTO, which inherits its ID from GuidEntity, a command
        /// can declare an ID of its own.
        /// </summary>
        public static MemberInfo[] GetCommandMembers(this Type @this)
        {
            return @this.GetPropertiesAndFields(BindingFlags.Public | BindingFlags.Instance)
                 .ExceptNull()
                 .Except(x => x.IsInheritedFromTheBaseClass())
                 .ToArray();
        }

        public static Type[] GetFiledTypes(this Type @this)
        {
            return @this.GetCommandMembers()
                 .Select(x => x.GetPropertyOrFieldType())
                 .ToArray();
        }

        /// <summary>
        /// Gets the nested types which the command class declares one of its own for, i.e. the
        /// nested classes. A nested enum is generated by DtoTypes into Enums.cs instead, because an
        /// enum is not a class: generating one here produced a class holding its value__ field.
        /// </summary>
        public static Type[] GetCommandNestedTypes(this Type @this)
            => @this.GetNestedTypes().Except(x => x.IsEnum).ToArray();

        /// <summary>
        /// Determines whether the specified member is declared by EventBusMessage, such as
        /// DeduplicationId. The generated command inherits those, so re-declaring them would hide them.
        /// </summary>
        /// <remarks>
        /// The declaring type is matched by name because the command assembly can be compiled
        /// against a different version of Olive.EventBus than this generator.
        /// </remarks>
        static bool IsInheritedFromTheBaseClass(this MemberInfo @this)
            => @this.DeclaringType?.FullName == GeneratedBaseClass;
    }
}